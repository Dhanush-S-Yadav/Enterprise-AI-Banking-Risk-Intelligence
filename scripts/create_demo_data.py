def render(d):
    stem,title,category,code,version,date,owner,purpose,controls,examples=d
    header=(f'Title: {title}\nPolicy ID: {code}\nVersion: {version}\nEffective Date: {date}\n'
            f'Category: {category}\nDocument Owner: {owner}\nClassification: SYNTHETIC / TRAINING ONLY\n\n')
    blocks=[('1. Purpose and Applicability',purpose+' This standard is internal to the imaginary Atlas Demo Bank and must not be treated as law, a real bank policy, or advice to customers.'),
            ('2. Roles and Responsibilities',f'The {owner} owns the document and maintains an evidence trail. Front-line personnel gather records, reviewers validate conditions, and managers approve documented exceptions according to their role.'),
            ('3. Required Controls','\n'.join(f'3.{n} {text}' for n,text in enumerate(controls,1))),
            ('4. Synthetic Case Examples','\n'.join(f'4.{n} {text}' for n,text in enumerate(examples,1))),
            ('5. Evidence and Audit Requirements',f'For all relevant {category.lower()} activities, retain the case identifier, document version, reviewer, date, control result, evidence reference, and any exception rationale. A missing document is an evidence gap; it does not prove control compliance or misconduct.'),
            ('6. Escalation and Human Judgment','Where a condition is unclear, employees must seek review by the designated owner. The example thresholds are invented for a learning project and cannot be used to decide actual banking services.'),
            ('7. Limitations',f'This document is synthetic. It does not represent an actual bank, regulator, statute, customer account, production incident, or live transaction. Any AI-generated summary must cite this source and acknowledge missing evidence.')]
    return header+'\n\n'.join(f'{heading}\n{body}' for heading,body in blocks)+'\n'

